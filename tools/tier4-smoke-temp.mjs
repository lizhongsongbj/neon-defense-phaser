import { chromium } from 'playwright-core'
const browser=await chromium.launch({executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',headless:true})
const page=await browser.newPage({viewport:{width:1280,height:800}})
const errors=[]
page.on('pageerror',e=>errors.push(String(e)))
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
await page.goto('http://127.0.0.1:5174/',{waitUntil:'networkidle'})
await page.evaluate(()=>localStorage.clear())
await page.reload({waitUntil:'networkidle'})
await page.click('#start-game')
await page.waitForSelector('#deploy-mission:not([disabled])',{timeout:20000})
await page.click('#deploy-mission')
await page.click('[data-loadout-confirm]')
await page.waitForTimeout(1500)
const canvas=await page.locator('#game-canvas canvas').boundingBox()
if(!canvas) throw new Error('canvas missing')
const clickSlot=()=>page.mouse.click(canvas.x+467/1280*canvas.width,canvas.y+128/800*canvas.height)
await clickSlot()
await page.waitForSelector('#tower-picker:not([hidden])')
await page.locator('.tower-option').first().click()
await page.waitForTimeout(300)
await clickSlot()
await page.waitForSelector('#tower-actions:not([hidden])')
await page.click('#tower-upgrade')
await page.waitForTimeout(150)
await page.click('#tower-upgrade')
await page.waitForTimeout(250)
const before=await page.evaluate(()=>({name:document.querySelector('#tower-actions-name')?.textContent,branches:document.querySelectorAll('.tower-tier4-branch').length,upgradeHidden:document.querySelector('#tower-upgrade')?.hidden}))
await page.locator('.tower-tier4-branch').first().click()
await page.waitForTimeout(350)
const after=await page.evaluate(()=>({name:document.querySelector('#tower-actions-name')?.textContent,branches:document.querySelectorAll('.tower-tier4-branch').length,toast:document.querySelector('#wave-toast')?.textContent,stored:localStorage.getItem('neon-defense-save-v2')}))
await page.screenshot({path:'tools/smoke-shots/tier4-upgrade.png'})
console.log(JSON.stringify({before,after,errors},null,2))
await browser.close()
if(errors.length||before.branches!==2||!before.upgradeHidden||!after.name?.includes('LV.4')||after.branches!==0||!after.stored?.includes('tier4BranchId'))process.exit(1)